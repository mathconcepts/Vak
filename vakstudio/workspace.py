"""Pack folders, manifest (the harness's memory), run log (observability) and approvals (guardrail).

packs/<id>/
  manifest.json   decisions + state; any model or person reads the same file, so switching models loses nothing
  text.md         the prayer text (source of truth, written by a person)
  text.json       parsed text (generated)
  audio/          the recording + 16 kHz copy   (never leaves this computer unless the licence allows)
  work/           emissions cache, timing.json, judge.json, previews
  pack.json       what the Reader loads (generated by build)
  approvals/      one file per approved build, written only by `vak approve` (a person at the keyboard)
runs/YYYY-MM-DD.jsonl   one line per tool call
dist/           built HTML files
"""
import datetime, hashlib, json, os, re, time

ROOT = os.environ.get("VAK_HOME") or os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PACKS = os.path.join(ROOT, "packs")
DIST = os.path.join(ROOT, "dist")
RUNS = os.path.join(ROOT, "runs")
ID_RE = re.compile(r"^[a-z0-9][a-z0-9-]{1,40}$")

EDITABLE = {"title", "sub", "source", "bite", "bite_end", "order", "anchors", "licence", "judge", "notes", "language_hint"}


class VakError(Exception):
    """A named, user-facing error. `code` is one of the names in the plan's error map."""
    def __init__(self, code, msg, **extra):
        super().__init__(msg)
        self.code, self.msg, self.extra = code, msg, extra

    def as_dict(self):
        return {"ok": False, "error": self.code, "message": self.msg, **self.extra}


def pdir(pid, *parts):
    if not ID_RE.match(pid or ""):
        raise VakError("BadPackId", f"Pack id must be lowercase letters, digits and dashes: {pid!r}")
    return os.path.join(PACKS, pid, *parts)


def inside(path, base):
    """Guardrail: tools only write inside packs/ and dist/."""
    rp, rb = os.path.realpath(path), os.path.realpath(base)
    if not (rp == rb or rp.startswith(rb + os.sep)):
        raise VakError("PathOutsideWorkspace", f"Refusing to write outside {base}: {path}")
    return path


def load(pid):
    p = pdir(pid, "manifest.json")
    if not os.path.exists(p):
        raise VakError("PackNotFound", f"No pack named {pid}. Create it with pack_new.")
    for sub in ("audio", "work", "approvals"):        # empty folders do not survive git clone
        os.makedirs(pdir(pid, sub), exist_ok=True)
    return json.load(open(p, encoding="utf-8"))


def save(pid, m):
    m["updated"] = now()
    p = inside(pdir(pid, "manifest.json"), PACKS)
    tmp = p + ".tmp"
    json.dump(m, open(tmp, "w", encoding="utf-8"), ensure_ascii=False, indent=2)
    os.replace(tmp, p)


def now():
    return datetime.datetime.now().astimezone().isoformat(timespec="seconds")


def list_ids():
    if not os.path.isdir(PACKS):
        return []
    return sorted(d for d in os.listdir(PACKS) if os.path.exists(os.path.join(PACKS, d, "manifest.json")))


def log(tool, args, ok, result=None, t0=None, error=None):
    os.makedirs(RUNS, exist_ok=True)
    safe = {k: (v if isinstance(v, (int, float, bool)) or v is None else str(v)[:200]) for k, v in (args or {}).items()}
    rec = {"ts": now(), "tool": tool, "args": safe,
           "args_hash": hashlib.sha256(json.dumps(safe, sort_keys=True).encode()).hexdigest()[:12],
           "ok": ok, "secs": round(time.time() - t0, 2) if t0 else None}
    if error:
        rec["error"] = error
    if isinstance(result, dict):
        rec["gates"] = {k: v.get("ok") for k, v in result.get("gates", {}).items()} if "gates" in result else None
    with open(os.path.join(RUNS, datetime.date.today().isoformat() + ".jsonl"), "a", encoding="utf-8") as f:
        f.write(json.dumps(rec, ensure_ascii=False) + "\n")


def parse_order(spec, n):
    """'0-3,9-12,25-389,9-12' → [0,1,2,3,9,...]. Lists pass through. None → all lines."""
    if spec is None:
        return list(range(n))
    if isinstance(spec, list):
        return [int(x) for x in spec]
    out = []
    for part in str(spec).replace(" ", "").split(","):
        if not part:
            continue
        if "-" in part:
            a, b = part.split("-")
            out += list(range(int(a), int(b) + 1))
        else:
            out.append(int(part))
    bad = [x for x in out if not 0 <= x < n]
    if bad:
        raise VakError("BadOrder", f"Order mentions lines that do not exist (text has {n} lines): {bad[:5]}")
    return out


def file_hash(*paths):
    h = hashlib.sha256()
    for p in paths:
        if p and os.path.exists(p):
            h.update(open(p, "rb").read())
    return h.hexdigest()[:16]
